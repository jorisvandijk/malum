import AppKit
import MalumCore

/// The general pasteboard, watched by its change count.
@MainActor
public final class PasteboardClipboard: Clipboard {
    /// Copies marked with these are never read (nspasteboard.org's convention): password managers
    /// mark secrets concealed, and transient or generated copies aren't meant to be kept.
    private static let skippedTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"),
    ]
    /// How often the change count is looked at, in seconds.
    private static let pollSeconds = 0.5
    /// How late a look may come, in seconds, so macOS can bundle the wake-ups.
    private static let pollTolerance = 0.1
    /// How long after the popup closes cmd+V goes out, in seconds, so it reaches the app below.
    private static let pasteDelay = 0.05

    /// The pasteboard.
    private let pasteboard = NSPasteboard.general
    /// The change count last seen.
    private var lastChange = 0
    /// Looks at the change count.
    private var timer: Timer?
    /// Where copies go.
    private var onCopy: (@MainActor (CopySeen) -> Void)?

    /// Creates the clipboard, not watching yet.
    public init() {}

    /// Whether Paste from Other Apps is set to deny. Before macOS 15.4 there's no such setting.
    public var isDenied: Bool {
        guard #available(macOS 15.4, *) else { return false }
        return pasteboard.accessBehavior == .alwaysDeny
    }

    /// Starts looking at the change count twice a second.
    public func watch(_ onCopy: @escaping @MainActor (CopySeen) -> Void) {
        stopWatching()
        self.onCopy = onCopy
        lastChange = pasteboard.changeCount
        let timer = Timer(timeInterval: Self.pollSeconds, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.look() }
        }
        timer.tolerance = Self.pollTolerance
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Stops looking.
    public func stopWatching() {
        timer?.invalidate()
        timer = nil
        onCopy = nil
    }

    /// Writes `entry` to the pasteboard, and takes the new change count as seen.
    public func put(_ entry: ClipEntry, image: Data?) -> Bool {
        pasteboard.clearContents()
        let items = PasteboardItems.items(for: entry, image: image)
        let written = !items.isEmpty && pasteboard.writeObjects(items)
        lastChange = pasteboard.changeCount
        return written
    }

    /// Sends cmd+V a moment later, once the popup has given the keys back.
    public func paste() {
        Timer.scheduledTimer(withTimeInterval: Self.pasteDelay, repeats: false) { _ in
            MainActor.assumeIsolated { SyntheticKeys.paste() }
        }
    }

    /// Reads the pasteboard when it changed since the last look.
    private func look() {
        let change = pasteboard.changeCount
        guard change != lastChange else { return }
        lastChange = change
        let types = pasteboard.types ?? []
        if let skipped = types.first(where: Self.skippedTypes.contains) {
            onCopy?(.skipped(skipped.rawValue))
            return
        }
        guard let copy = PasteboardItems.copy(from: pasteboard, types: types) else { return }
        onCopy?(.copied(copy))
    }
}
