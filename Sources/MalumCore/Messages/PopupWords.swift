/// The popup panel's own words: its buttons and what screen readers say for its pictures.
public enum PopupWords {
    /// The button that empties a list.
    public static let clearAll = "Clear all"
    /// The same button after one click, asking for a second.
    public static let confirmClear = "Click again to clear"
    /// The magnifying glass in front of the search field.
    public static let search = "Search"
    /// The button that deletes one row, and its tooltip.
    public static let delete = "Delete (cmd+backspace)"
}
